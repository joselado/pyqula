"""The quantics tensor-train BSE solver.

The chain being tested is: PairOracle evaluates the pair basis one
k-point at a time; LazyKernel gives any matrix element of X - D from it;
qutecipy cross-interpolates that into an MPO; pyitensor's DMRG
diagonalizes it. Each link is pinned separately against something exact,
because a failure anywhere in it looks the same from the outside -- a
plausible number that is slightly wrong.

There is no comparable open implementation to benchmark against (Xatu,
whose formalism bsetk/ follows, uses a dense solver; TensorBinding, the
closest tensor-network tight-binding code, has no exciton module), so the
substitutes are internal: the dense solver where it still runs, and the
matrix-free solver -- exact, and independent of every tensor-train choice
-- past that.
"""
import numpy as np
import pytest

pytest.importorskip("dmrgpy", reason="the quantics BSE solver uses "
                    "dmrgpy.pyitensor's DMRG")

from testutils import gapped_ionic_chain, gapped_honeycomb
from pyqula import geometry
from pyqula.bsetk.interaction import density_interaction, bare_interaction
from pyqula.bsetk.pairbasis import PairBasis
from pyqula.bsetk.oracle import PairOracle
from pyqula.bsetk.factorize import KernelFactorization
from pyqula.bsetk import qtt


def spinless_chain(stagger=0.9):
    """A gapped, spinless, NON-degenerate two-band chain. Spinless keeps
    the tensor-train ranks small enough for a fast test; the degenerate
    spinful case is covered by test_bse_gauge.py's rank measurements and
    by test_qtt_spinful_matches_dense below."""
    g = geometry.chain().supercell(2)
    h = g.get_hamiltonian(has_spin=False)
    h.add_onsite(lambda r: stagger * (-1) ** int(round(r[0] - 0.5)))
    return h.get_multicell().get_dense()


def mpo_to_dense(mpo):
    """Contract an MPO back to a matrix. Tests only, obviously."""
    from dmrgpy.pyitensor.tensor import commonIndex
    res = np.ones((1, 1, 1), dtype=np.complex128)  # (row, col, bond)
    for i in range(1, mpo.length() + 1):
        T = mpo.A(i)
        s = [x for x in T.inds if x.hastags("Site")]
        s0 = [x for x in s if x.plev == 0][0]   # unprimed = ket = column
        s1 = [x for x in s if x.plev == 1][0]   # primed   = bra = row
        l = commonIndex(mpo.A(i), mpo.A(i - 1)) if i > 1 else None
        r = commonIndex(mpo.A(i), mpo.A(i + 1)) if i < mpo.length() else None
        a = T.transpose_to([x for x in (l, s0, s1, r) if x is not None])
        if l is None: a = a[None]
        if r is None: a = a[..., None]
        res = np.einsum("MNl,lnmr->MmNnr", res, a)
        res = res.reshape(res.shape[0] * res.shape[1],
                          res.shape[2] * res.shape[3], res.shape[4])
    return res[:, :, 0]


# ---------------------------------------------------------------- oracle

@pytest.mark.parametrize("gauge", [None, "phase", "projection"])
def test_oracle_reproduces_the_pair_basis(gauge):
    """PairOracle must produce exactly what PairBasis does, k-point by
    k-point -- including the mesh ordering, which it regenerates from the
    index instead of calling geometry.get_kmesh"""
    h = spinless_chain()
    nk = 8
    pb = PairBasis(h, Q=[0.25, 0., 0.], nk=nk, gauge=gauge)
    po = PairOracle(h, Q=[0.25, 0., 0.], nk=nk, gauge=gauge, coarse_nk=nk)
    assert po.npair == pb.npair
    assert po.vbands == pb.vbands and po.cbands == pb.cbands
    ks = np.array([po.kpoint(i) for i in range(nk)])
    assert np.max(np.abs(ks - pb.kpoints)) < 1e-14
    dE, el, ho = po.pair_arrays(np.arange(po.npair))
    assert np.max(np.abs(dE - pb.dE)) < 1e-12
    assert np.max(np.abs(el - pb.el)) < 1e-12
    assert np.max(np.abs(ho - pb.ho)) < 1e-12


def test_oracle_mesh_order_matches_get_kmesh_in_2d():
    """The k index is generated by bit arithmetic, so its correspondence
    to geometry.get_kmesh's own ordering is an assumption that has to be
    checked rather than believed -- in 2D above all, where a transposed
    convention would still give a plausible spectrum"""
    h = gapped_honeycomb(spinful=False)
    nk = 8
    po = PairOracle(h, nk=nk, coarse_nk=nk)
    ref = np.array(h.geometry.get_kmesh(nk=nk))
    got = np.array([po.kpoint(i) for i in range(nk * nk)])
    assert np.max(np.abs(got - ref)) < 1e-14


