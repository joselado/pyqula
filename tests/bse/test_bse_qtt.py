def test_qtt_matches_dense_chain():
    h = spinless_chain()
    V = density_interaction(h, V1=0.8)
    for nk in (8, 16, 32):
        ref = h.get_bse(V=V, nk=nk, tda=True).get_energies(n=1)[0].real
        got = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                        tolerance=1e-10, coarse_nk=8).get_energies()[0].real
        assert abs(got - ref) < 1e-8, (nk, got, ref)


@pytest.mark.parametrize("nk", [1024, 4096])
def test_qtt_matches_iterative_past_the_dense_wall(nk):
    """The comparison that stays available as the mesh grows.

    bsetk/iterative.py applies the exact kernel and is independent of
    every tensor-train choice made here -- the gauge, the cross
    interpolation, the MPO, DMRG -- so agreement between the two is a real
    check rather than two versions of the same code agreeing. At these
    mesh sizes the dense solver is already out of reach."""
    h = spinless_chain()
    V = density_interaction(h, V1=0.8)
    ref = h.get_bse(V=V, nk=nk, tda=True, solver="iterative",
                    neig=1).get_energies()[0].real
    b = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                  tolerance=1e-10, coarse_nk=8)
    assert abs(b.get_energies()[0].real - ref) < 1e-7


def test_qtt_diagonalizes_far_fewer_k_points_than_the_mesh():
    """The claim the whole solver exists for.

    Cross interpolation visits a number of k-points set by the
    tensor-train rank, not by the mesh, so refining the mesh 16-fold must
    not cost 16 times the diagonalizations. Measured on this model, number
    of k-points actually diagonalized against the mesh size:

      nk      256  1024  4096  16384  65536  262144
      ndiag   256  1021  2767   5051   6717    7455

    i.e. growing like log(nk) while the mesh grows by a factor of 1024,
    with the wall time flat at 15-18 s throughout."""
    h = spinless_chain()
    V = density_interaction(h, V1=0.8)
    ndiag = []
    for nk in (4096, 65536):
        b = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                      tolerance=1e-8, coarse_nk=8)
        ndiag.append(b.pairs.ndiag())
    assert ndiag[1] < 4 * ndiag[0], ndiag        # far from 16x
    assert ndiag[1] < 65536 / 8, ndiag           # and far below the mesh


def test_qtt_binding_energy_needs_no_mesh_scan():
    """The lowest independent-particle transition, which the binding
    energy is measured from, is the ground state of the diagonal MPO --
    not a minimum over a mesh nobody ever built"""
    h = spinless_chain()
    V = density_interaction(h, V1=0.8)
    nk = 32
    ref = h.get_bse(V=V, nk=nk, tda=True)
    got = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                    tolerance=1e-10, coarse_nk=8)
    assert abs(got.get_lowest_transition()
               - np.min(ref.pairs.dE)) < 1e-8
    assert abs(got.get_binding_energies()[0]
               - ref.get_binding_energies(n=1)[0].real) < 1e-7
    assert got.get_binding_energies()[0] > 0.  # actually bound


