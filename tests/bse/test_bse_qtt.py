@pytest.mark.parametrize("kernel", ["full", "direct", "exchange"])
def test_lazy_kernel_matches_the_dense_kernel(kernel):
    h = spinless_chain()
    W = bare_interaction(h, V=density_interaction(h, V1=0.8, V2=0.3))
    nk = 8
    pb = PairBasis(h, Q=[0.25, 0., 0.], nk=nk, gauge="projection")
    po = PairOracle(h, Q=[0.25, 0., 0.], nk=nk, gauge="projection",
                    coarse_nk=nk)
    f = KernelFactorization(pb, W, Wx=W, kernel=kernel, block="A")
    ref = f.to_dense() - np.diag(f.diag)   # the interaction part alone
    lk = qtt.LazyKernel(po, W, Wx=W, kernel=kernel)
    got = np.array([[lk.element(m, n) for n in range(po.npair)]
                    for m in range(po.npair)])
    assert np.max(np.abs(got - ref)) < 1e-13


@pytest.mark.parametrize("nk", [8, 16])
def test_mpo_reproduces_the_dense_block(nk):
    """The MPO is built by cross-interpolating matrix elements, never by
    decomposing a matrix -- so that it reproduces the matrix is a real
    check, not a tautology"""
    h = spinless_chain()
    W = bare_interaction(h, V=density_interaction(h, V1=0.8))
    pb = PairBasis(h, nk=nk, gauge="projection")
    po = PairOracle(h, nk=nk, gauge="projection", coarse_nk=nk)
    ref = KernelFactorization(pb, W, Wx=W, kernel="full",
                              block="A").to_dense()
    lk = qtt.LazyKernel(po, W, Wx=W, kernel="full")
    grid = qtt.quantics_grid(po)
    mpo = qtt.build_mpo(lk, grid, tolerance=1e-12)
    assert np.max(np.abs(mpo_to_dense(mpo) - ref)) < 1e-10


def test_grid_index_is_the_pair_index():
    """quantics grid index <-> flat pair index, in 2D with band sites.
    Getting this wrong permutes the whole problem silently."""
    h = gapped_honeycomb(spinful=True)   # 2 valence, 2 conduction bands
    po = PairOracle(h, nk=4, coarse_nk=4)
    grid = qtt.quantics_grid(po)
    seen = set()
    for m in range(po.npair):
        ik = m // po.nband
        ib = m % po.nband
        iv, ic = divmod(ib, len(po.cbands))
        ix, iy = divmod(ik, po.nk)
        gi = (ix, iy) + _digits(iv, grid.pyqula_vsizes) \
                      + _digits(ic, grid.pyqula_csizes)
        assert qtt.grid_to_pair(grid, gi) == m, (m, gi)
        seen.add(qtt.grid_to_pair(grid, gi))
    assert len(seen) == po.npair          # a bijection, not just injective


def _digits(i, sizes):
    """Mixed-radix digits of i for the given per-variable sizes"""
    out = []
    for s in reversed(sizes):
        i, r = divmod(i, s)
        out.append(r)
    return tuple(reversed(out))


@pytest.mark.parametrize("nv,nc", [(1, 1), (2, 2)])
def test_band_index_is_split_across_sites(nv, nc):
    """A band window must not sit on one site of dimension nv*nc: that
    site becomes (nv*nc)^2 wide in the MPO, and cross interpolation has to
    sample all of it per pivot. Factorizing keeps every site at the
    largest prime factor instead."""
    h = gapped_honeycomb(spinful=True)
    po = PairOracle(h, nk=4, coarse_nk=4, nv=nv, nc=nc)
    grid = qtt.quantics_grid(po)
    dims = list(grid.localdimensions())
    assert int(np.prod(dims)) == po.npair       # still the same problem
    band_dims = dims[2 * 2:]                    # after the 2x2 k-bits
    assert int(np.prod(band_dims)) == nv * nc
    if band_dims:
        assert max(band_dims) <= max(max(_pf(nv)), max(_pf(nc)))


def test_supercell_band_window_is_not_one_wide_site():
    """The case that motivated the factorization: a 3x3 supercell of the
    honeycomb has 9 valence and 9 conduction bands. On one site that is a
    band index of 81, and 6561 once the MPO fuses row and column. Split
    and factorized it is four sites of 3, i.e. 9 in the MPO."""
    from pyqula import geometry
    g = geometry.honeycomb_lattice().supercell(3)
    h = g.get_hamiltonian(has_spin=False)
    h.add_sublattice_imbalance(0.8)
    h = h.get_multicell().get_dense()
    po = PairOracle(h, nk=4, coarse_nk=4)
    assert len(po.vbands) == 9 and len(po.cbands) == 9
    grid = qtt.quantics_grid(po)
    band_dims = list(grid.localdimensions())[2 * 2:]
    assert band_dims == [3, 3, 3, 3], band_dims
    assert max(band_dims) ** 2 == 9              # widest MPO site, not 6561


def _pf(n):
    return [b for b, r in qtt.prime_factors(n)] or [1]


def test_prime_factorization_of_the_band_window():
    for n, want in [(1, 1), (2, 2), (4, 4), (6, 6), (7, 7), (8, 8), (9, 9),
                    (81, 81)]:
        f = qtt.prime_factors(n)
        assert int(np.prod([b ** r for b, r in f])) == want
    assert qtt.prime_factors(1) == []
    assert qtt.prime_factors(9) == [(3, 2)]     # two sites of 3, not one of 9
    assert qtt.prime_factors(8) == [(2, 3)]


