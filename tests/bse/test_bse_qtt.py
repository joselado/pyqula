def test_excited_excitons_are_refused():
    """The overlap-penalty DMRG does not converge on this problem -- it
    returned energies up to 0.4 off, and sometimes below the true
    eigenvalue, at every penalty weight tried -- so neig>1 is refused
    rather than approximated. See solve_qtt's message for the numbers."""
    h = spinless_chain()
    V = density_interaction(h, V1=0.8)
    with pytest.raises(ValueError, match="lowest exciton only"):
        h.get_bse(V=V, nk=8, tda=True, solver="qtt", neig=3)


@pytest.mark.parametrize("unfolding", ["grouped", "interleaved"])
def test_both_bit_orderings_give_the_same_answer(unfolding):
    """The bit ordering is a representation choice, so it changes the
    ranks (grouped measured lower on every 2D case) and must not change
    the answer"""
    h = gapped_honeycomb(spinful=False)
    V = density_interaction(h, V1=0.6, V2=0.2)
    nk = 8
    ref = h.get_bse(V=V, nk=nk, tda=True).get_energies(n=1)[0].real
    got = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                    tolerance=1e-10, coarse_nk=4, maxdim=200,
                    unfolding=unfolding).get_energies()[0].real
    assert abs(got - ref) < 1e-6, (unfolding, got, ref)


def test_qtt_amplitudes_are_the_eigenvector():
    """The returned amplitudes must actually solve the problem, not just
    have the right shape"""
    h = spinless_chain()
    W = bare_interaction(h, V=density_interaction(h, V1=0.8))
    V = density_interaction(h, V1=0.8)
    nk = 16
    # coarse_nk=nk so the oracle picks its gauge references off the same
    # mesh PairBasis does: the amplitudes of two different gauges differ
    # by a diagonal unitary and are eigenvectors of two different (though
    # isospectral) matrices, so comparing them across gauges is meaningless
    b = h.get_bse(V=V, nk=nk, tda=True, solver="qtt", neig=1,
                  tolerance=1e-12, coarse_nk=nk)
    pb = PairBasis(h, nk=nk, gauge="projection")
    f = KernelFactorization(pb, W, Wx=W, kernel="full", block="A")
    x = b.amplitudes[0]
    x = x / np.linalg.norm(x)
    e = b.get_energies()[0].real
    assert np.linalg.norm(f.matvec(x) - e * x) < 1e-6


